#!/usr/bin/env python3

from pathlib import Path
from dataclasses import dataclass

import argparse
import coloredlogs
import logging
import sys
import re

#
# Logger
#
LOGGER: logging.Logger

#
# Target INF Lines
#
INF_STRING_REPLACEMENTS = {
    r"INF_VERSION\s*=": "INF_VERSION                    =",
    r"BASE_NAME\s*=": "BASE_NAME                      =",
    r"FILE_GUID\s*=": "FILE_GUID                      =",
    r"MODULE_TYPE\s*=": "MODULE_TYPE                    =",
    r"VERSION_STRING\s*=": "VERSION_STRING                 =",
    r"ENTRY_POINT\s*=": "ENTRY_POINT                    =",
    r"   RAW\|": "  RAW|",
    r"   TE\|": "  TE|",
    r"   DXE_DEPEX\|": "  DXE_DEPEX|",
    r"   PE32\|": "  PE32|",
}

@dataclass
class CleanContext:
    device: str

def clean_inf_files (bin_path: Path):
    # Go thru all .inf Files
    for file in bin_path.rglob ("*.inf"):
        try:
            # Get File Contents
            content = file.read_text (encoding="utf-8")
        except:
            # Report Read Error
            LOGGER.error (f"Failed to Read File Contents of \"{file}\"!")
            continue

        # Verify Clean State
        if "AUTOGENERATED" not in content:
            continue

        # Remove Header & Footer
        content = "".join (content.splitlines (keepends=True)[6:-2])

        # Replace Target Lines
        for pattern, replacement in INF_STRING_REPLACEMENTS.items ():
            content = re.sub (pattern, replacement, content)

        try:
            # Write Changes
            file.write_text (content, encoding="utf-8")
        except:
            LOGGER.error (f"Failed to Write Changes to the File: \"{file}\"!")
            continue

        # Show Progress
        LOGGER.info (f"Cleaned: {file}")

def remove_files (bin_path: Path):
    # Go thru all .inc Files
    for file in bin_path.rglob ("*.inc"):
        try:
            # Delete .File
            file.unlink (missing_ok=True)

            # Show Deleted File
            LOGGER.info (f"Deleted: {file}")
        except:
            LOGGER.error (f"Failed to Delete \"{file}\"!")

def parse_arguments () -> CleanContext:
    # Create Argument Parser
    parser = argparse.ArgumentParser (description="Cleans the Binary Files of the Specified Device.")

    # Add Script Arguments
    parser.add_argument ("-d", "--device", type=str, required=True, help="Defines the Device to Clean the Binaries of.")

    # Parse Script Arguments
    args = parser.parse_args ()

    # Return Class
    return CleanContext (
        device = args.device
    )

def setup_logger ():
    global LOGGER

    # Create Logger
    LOGGER = logging.getLogger (sys.argv[0])

    # Set Logger Attributes
    coloredlogs.install (
        level="INFO",
        fmt="%(message)s",
        level_styles={
            "info": {
                "color": "white"
            },

            "error": {
                "color": "red"
            }
        }
    )

def main ():
    # Setup Logger
    setup_logger ()

    # Parse Script Arguments
    ctx = parse_arguments ()

    # Set Binary Path
    bin_path = Path (ctx.device)

    # Verify Binary Path Existence
    if not bin_path.exists ():
        LOGGER.info ("The Specified Device has no Binary Folder.")
        sys.exit (1)

    # Remove Unnecessary Files
    remove_files (bin_path)

    # Clean INF Files
    clean_inf_files (bin_path)

if __name__ == "__main__":
    main ()
